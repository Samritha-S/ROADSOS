  static Future<void> insertAll(Database db) async {
    // 1. Insert Country Configs
    for (final config in CountryConfigModel.defaults) {
      await db.insert(
        'country_configs',
        config.toMap(),
        conflictAlgorithm: ConflictAlgorithm.replace,
      );
    }

    // 2. Insert NH-544 Facilities
    final facilities = getSeedFacilities();
    for (final facility in facilities) {
      await db.insert(
        'facilities',
        facility.toMap(),
        conflictAlgorithm: ConflictAlgorithm.replace,
      );
    }
  }
